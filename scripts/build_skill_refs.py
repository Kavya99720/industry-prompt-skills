#!/usr/bin/env python
"""Copy an industry's source files into its skill's references/ folder, so the skill is self-contained.

Usage:
  python scripts/build_skill_refs.py --industry healthcare           write the copies
  python scripts/build_skill_refs.py --industry healthcare --check   exit 1 if any copy is missing, stale or extra

Copied (the originals stay the source of truth; never edit the copies):
  industries/<x>/core.md                      -> references/core.md
  industries/<x>/workflows/NN-*.md            -> references/workflows/   (written workflows only; README and stubs are skipped)
  docs/shared/section-bases.md                -> references/shared/section-bases.md
  docs/shared/variables.json                  -> references/shared/variables.json
  docs/shared/baseline-rules.md               -> references/shared/baseline-rules.md
  docs/shared/platform-contract.md            -> references/shared/platform-contract.md
  industries/<x>/section-bases.md (optional)  -> references/industry/section-bases.md
  industries/<x>/variables.json (optional)    -> references/industry/variables.json
A generated references/INDEX.md lists the copies. Test profiles, eval files and results are never copied.
Standard library only.
"""
import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHARED = ("section-bases.md", "variables.json", "baseline-rules.md", "platform-contract.md")
# Optional, written by the industry: its own section base text and its custom-detail variables.
OPTIONAL_INDUSTRY = ("section-bases.md", "variables.json")


def is_stub(text):
    return "Status: stub" in text[:600]


def plan(industry, root=ROOT):
    """Return {destination path relative to references/: (source path relative to root, text)}."""
    ind = Path("industries") / industry
    files = {}
    core = ind / "core.md"
    files["core.md"] = core
    wf = root / ind / "workflows"
    if wf.is_dir():
        for f in sorted(wf.glob("*.md")):
            if f.name.lower() == "readme.md":
                continue
            if is_stub(f.read_text(encoding="utf-8")):
                continue
            files[f"workflows/{f.name}"] = ind / "workflows" / f.name
    for name in SHARED:
        files[f"shared/{name}"] = Path("docs/shared") / name
    for name in OPTIONAL_INDUSTRY:
        if (root / ind / name).is_file():
            files[f"industry/{name}"] = ind / name
    out = {}
    for dest, src in files.items():
        p = root / src
        if not p.is_file():
            raise FileNotFoundError(f"missing source: {src.as_posix()}")
        out[dest] = (src, p.read_text(encoding="utf-8"))
    lines = [
        f"# {industry} skill references (generated)",
        "",
        "Generated by scripts/build_skill_refs.py. Do not edit: change the source file and run the script again.",
        "A test fails when a copy is out of sync.",
        "",
        "| Copy | Source |",
        "|---|---|",
    ]
    lines += [f"| {d} | {s.as_posix()} |" for d, (s, _) in out.items()]
    out["INDEX.md"] = (None, "\n".join(lines) + "\n")
    return out


def target_dir(industry, root=ROOT):
    return root / ".claude" / "skills" / f"{industry}-prompt-writer" / "references"


def problems(industry, root=ROOT):
    wanted = plan(industry, root)
    tdir = target_dir(industry, root)
    found = []
    for dest, (_, text) in wanted.items():
        p = tdir / dest
        if not p.is_file():
            found.append(f"missing: references/{dest}")
        elif p.read_text(encoding="utf-8") != text:
            found.append(f"out of sync: references/{dest}")
    if tdir.is_dir():
        for p in sorted(tdir.rglob("*")):
            rel = p.relative_to(tdir).as_posix()
            if p.is_file() and rel not in wanted:
                found.append(f"extra file: references/{rel}")
    return found


def build(industry, root=ROOT):
    wanted = plan(industry, root)
    tdir = target_dir(industry, root)
    if tdir.is_dir():
        for p in sorted(tdir.rglob("*"), reverse=True):
            rel = p.relative_to(tdir).as_posix()
            if p.is_file() and rel not in wanted:
                p.unlink()
    for dest, (_, text) in wanted.items():
        p = tdir / dest
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8", newline="\n")
    return sorted(wanted)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--industry", required=True)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--root", default=str(ROOT))
    args = ap.parse_args(argv)
    root = Path(args.root)
    if args.check:
        found = problems(args.industry, root)
        for f in found:
            print(f)
        if found:
            print(f"{len(found)} problem(s). Run: python scripts/build_skill_refs.py --industry {args.industry}")
            return 1
        print(f"{args.industry} references are in sync")
        return 0
    names = build(args.industry, root)
    print(f"wrote {len(names)} files to .claude/skills/{args.industry}-prompt-writer/references/")
    return 0


if __name__ == "__main__":
    sys.exit(main())
